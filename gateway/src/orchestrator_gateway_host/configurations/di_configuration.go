func ConfigureDI() *dig.Container {
	container := dig.New()

	container.Provide(orchestrator_gateway_host_settings.NewHostSettings)

	orchestrator_configurations.AddOrchestratorConfiguration(container)
	orchestrator_db_configurations.AddOrchestratorDbConfiguration(container)
	orchestrator_vault_configurations.AddOrchestratorVaultConfiguration(container)
	orchestrator_redis_configurations.AddOrchestratorRedisConfiguration(container)
	orchestrator_gateway_configurations.AddOrchestratorGatewayConfiguration(container)
	orchestrator_blockchain_configurations.AddOrchestratorBlockchainConfiguration(container)
	orchestrator_gateway_mvc_configurations.AddOrchestratorGatewayMvcConfiguration(container)
	orchestrator_gateway_http_ipfs_configurations.AddOrchestratorGatewayHttpIpfsConfiguration(container)
	orchestrator_http_orchestrator_gateway_configurations.AddOrchestratorHttpOrchestratorGatewayConfiguration(container)
	orchestrator_gateway_http_platform_bridge_configurations.AddOrchestratorGatewayHttpPlatformBridgeConfiguration(container)
	orchestrator_gateway_http_agent_reasoning_llm_connector_configurations.AddOrchestratorGatewayHttpAgentReasoningLlmConnectorConfiguration(container)
	orchestrator_gateway_http_agent_identity_images_generator_configurations.AddOrchestratorGatewayHttpAgentIdentityImagesGeneratorConfiguration(container)
	orchestrator_gateway_http_agent_knowledge_database_connector_configurations.AddOrchestratorGatewayHttpAgentKnowledgeDatabaseConnectorConfiguration(container)

	return container
}
